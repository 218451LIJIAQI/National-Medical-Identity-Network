import { useState, useEffect, useCallback } from 'react'

export function useSessionState<T>(key: string, defaultValue: T | (() => T)) {
  const storageKey = `medlink:${key}`

  const readInitial = (): T => {
    try {
      const raw = sessionStorage.getItem(storageKey)
      if (raw !== null) {
        return JSON.parse(raw) as T
      }
    } catch {}
    return typeof defaultValue === 'function' ? (defaultValue as () => T)() : defaultValue
  }

  const [state, setState] = useState<T>(readInitial)

  useEffect(() => {
    setState(readInitial())
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [storageKey])

  const update = useCallback(
    (next: T | ((prev: T) => T)) => {
      setState((prev) => {
        const resolved = typeof next === 'function' ? (next as (p: T) => T)(prev) : next
        try {
          sessionStorage.setItem(storageKey, JSON.stringify(resolved))
        } catch {}
        return resolved
      })
    },
    [storageKey]
  )

  return [state, update] as const
}

export function downloadFile(filename: string, content: string, mimeType = 'text/plain;charset=utf-8') {
  const blob = new Blob([content], { type: mimeType })
  const url = URL.createObjectURL(blob)
  const link = document.createElement('a')
  link.href = url
  link.download = filename
  document.body.appendChild(link)
  link.click()
  document.body.removeChild(link)
  setTimeout(() => URL.revokeObjectURL(url), 1000)
}

export function exportToCsv(filename: string, headers: string[], rows: Array<Array<string | number | boolean>>) {
  const escapeCsv = (val: string | number | boolean) => {
    const str = String(val ?? '')
    if (str.includes(',') || str.includes('"') || str.includes('\n')) {
      return `"${str.replace(/"/g, '""')}"`
    }
    return str
  }

  const lines = [
    headers.map(escapeCsv).join(','),
    ...rows.map((r) => r.map(escapeCsv).join(',')),
  ]
  downloadFile(filename, lines.join('\n'), 'text/csv;charset=utf-8')
}

export function triggerPrintDocument(title: string, bodyHtml: string) {
  const printWin = window.open('', '_blank', 'width=840,height=720')
  if (!printWin) {
    window.print()
    return
  }
  printWin.document.write(`<!DOCTYPE html>
<html>
<head>
  <meta charset="utf-8" />
  <title>${title}</title>
  <style>
    body { font-family: system-ui, -apple-system, sans-serif; padding: 32px; color: #111827; line-height: 1.5; }
    h1 { font-size: 20px; margin: 0 0 4px; }
    h2 { font-size: 15px; margin: 20px 0 8px; border-bottom: 1px solid #e5e7eb; padding-bottom: 4px; }
    .meta { color: #6b7280; font-size: 13px; margin-bottom: 18px; }
    table { width: 100%; border-collapse: collapse; margin-top: 8px; font-size: 13px; }
    th, td { border: 1px solid #e5e7eb; padding: 8px 10px; text-align: left; }
    th { background: #f9fafb; font-weight: 600; }
    .footer { margin-top: 28px; font-size: 12px; color: #6b7280; border-top: 1px solid #e5e7eb; padding-top: 10px; }
  </style>
</head>
<body>
  ${bodyHtml}
  <div class="footer">Generated by MedLink MY Workstation • ${new Date().toLocaleString('en-MY')}</div>
  <script>window.onload = function() { window.print(); };</script>
</body>
</html>`)
  printWin.document.close()
}
